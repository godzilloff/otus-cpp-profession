/**
 * @file main.cpp
 * @brief Демонстрационная программа для библиотеки асинхронной обработки команд
 * 
 * Программа демонстрирует использование всех функций библиотеки async:
 * - connect() для создания контекстов обработки
 * - receive() для передачи команд на обработку  
 * - disconnect() для корректного завершения работы
 * 
 * @note Программа создает несколько контекстов обработки и передает команды
 *       различного формата для тестирования всех возможностей библиотеки.
 */

#include "../include/async.h"
#include <iostream>
#include <thread>
#include <chrono>
#include <vector>

/**
 * @brief Основная функция демонстрационной программы
 * @return int Код завершения программы (0 - успешное завершение)
 * 
 * Программа состоит из двух частей:
 * - Часть 1: Тестирование обработки команд с символами перевода строки
 * - Часть 2: Тестирование работы с динамическими блоками и автоматическим завершением
 * 
 * @warning Для корректной работы необходимо, чтобы библиотека async была 
 *          предварительно собрана и доступна для линковки.
 * 
 * @code
 * // Пример запуска программы
 * ./async_demo
 * @endcode
 */
int main() {
    std::cout << "Demo application started" << std::endl;
    std::cout << "Begin PART 1" << std::endl;
    
    // Часть 1: Тестирование обработки команд с символами перевода строки
    // и работы с несколькими контекстами одновременно
    /**
     * @brief Часть 1 - Тестирование базовой функциональности
     * 
     * Демонстрирует:
     * - Создание нескольких контекстов обработки
     * - Передачу команд, содержащих символы перевода строки
     * - Обработку команд в разных контекстах параллельно
     * - Использование динамических блоков с фигурными скобками
     * - Корректное завершение работы с освобождением ресурсов
     */
    std::size_t bulk = 5;
    auto h = async::connect(bulk);   ///< Первый контекст обработки с размером блока 5
    auto h2 = async::connect(bulk);  ///< Второй контекст обработки с размером блока 5
    
    // Передача команд в первый контекст
    async::receive(h, "1", 1);           ///< Простая команда "1"
    async::receive(h2, "1\n", 2);        ///< Команда "1" с переводом строки (второй контекст)
    async::receive(h, "\n2\n3\n4\n5\n6\n{\na\n", 15);  ///< Серия команд с переводами строк и началом динамического блока
    async::receive(h, "b\nc\nd\n}\n89\n", 11);         ///< Продолжение динамического блока и его завершение
    
    // Корректное завершение работы с контекстами
    async::disconnect(h);   ///< Освобождение ресурсов первого контекста
    async::disconnect(h2);  ///< Освобождение ресурсов второго контекста
    
     std::cout << "Begin PART 2" << std::endl;
    // Часть 2: Тестирование работы с динамическими блоками и автоматическим завершением
    /**
     * @brief Часть 2 - Тестирование динамических блоков и автоматического завершения
     * 
     * Демонстрирует:
     * - Автоматическое завершение блоков при достижении размера bulk_size
     * - Работу с динамическими блоками (команды в фигурных скобках)
     * - Обработку последовательности команд с паузами для визуального наблюдения
     * - Корректную обработку оставшихся команд при завершении
     */
    std::vector<std::string> test_commands = {
        "cmd1",     ///< Команда 1 - будет обработана в первом блоке
        "cmd2",     ///< Команда 2 - будет обработана в первом блоке  
        "cmd3",     ///< Команда 3 - завершит первый блок (размер блока = 3)
        "{",        ///< Начало динамического блока
        "cmd4",     ///< Команда 4 - внутри динамического блока
        "cmd5",     ///< Команда 5 - внутри динамического блока
        "}",        ///< Конец динамического блока (вызовет обработку команд 4-5)
        "cmd6",     ///< Команда 6 - начнет новый блок
        "cmd7",     ///< Команда 7 - продолжит текущий блок
        "cmd8",     ///< Команда 8 - завершит блок (размер блока = 3)
        "cmd9",     ///< Команда 9 - начнет новый блок
        "cmd10",    ///< Команда 10 - продолжит текущий блок
        "cmd11",    ///< Команда 11 - будет обработана при disconnect()
    };
    
    /**
     * @brief Создание контекста обработки с размером блока 3
     * 
     * Контекст будет автоматически завершать блоки при накоплении 3 команд,
     * если не находится внутри динамического блока.
     */
    void* handle = async::connect(2);
    
    /**
     * @brief Последовательная передача команд с задержками
     * 
     * Команды передаются одна за другой с задержкой 100 мс для возможности
     * визуального наблюдения за работой системы в реальном времени.
     * 
     * @note Задержки имитируют реальный ввод данных от пользователя
     * @note В продакшен-коде такие задержки обычно не используются
     */
    for (const auto& cmd : test_commands) {
        async::receive(handle, cmd.data(), cmd.size());
        std::this_thread::sleep_for(std::chrono::milliseconds(100));
    }
    
    /**
     * @brief Корректное завершение работы с контекстом
     * 
     * Вызывает обработку оставшихся команд (cmd11 в данном случае)
     * и освобождает все ресурсы, связанные с контекстом.
     * 
     * @warning Невызов disconnect() приведет к утечке ресурсов
     */
    async::disconnect(handle);
    
    std::cout << "Demo application finished" << std::endl;
    
    return 0;
}
