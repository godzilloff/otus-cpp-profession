/**
 * @file command_processor.h
 * @brief Заголовочный файл классов для многопоточной обработки команд
 * 
 * Содержит объявление классов ThreadPool и CommandProcessor для асинхронной
 * обработки пакетов команд с выводом в консоль и файлы.
 */

#pragma once

#include <vector>
#include <string>
#include <memory>
#include <mutex>
#include <queue>
#include <condition_variable>
#include <atomic>
#include <functional>
#include <thread>
#include <chrono>
#include <fstream>
#include <iostream>

/**
 * @brief Пул потоков для асинхронного выполнения задач
 * 
 * Обеспечивает выполнение задач в фиксированном количестве рабочих потоков.
 * Задачи ставятся в очередь и выполняются в порядке поступления.
 * 
 * @note Потокобезопасен - все операции защищены внутренними мьютексами
 * @note Автоматически управляет временем жизни рабочих потоков
 */
class ThreadPool {
public:
    /**
     * @brief Конструктор пула потоков
     * @param num_threads Количество рабочих потоков в пуле
     * @param name Имя пула для отладки и идентификации (опционально)
     * 
     * @warning Не рекомендуется создавать пулы с большим количеством потоков
     *          без необходимости, так как это может привести к избыточному
     *          потреблению ресурсов системы.
     * 
     * @code
     * // Пример создания пула с 2 потоками
     * ThreadPool pool(2, "FileWriter");
     * @endcode
     */
    explicit ThreadPool(size_t num_threads, const std::string& name = "");
    
    /**
     * @brief Деструктор пула потоков
     * 
     * Автоматически останавливает все рабочие потоки и дожидается их завершения.
     * Если в очереди остались невыполненные задачи, они будут проигнорированы.
     * 
     * @note Вызывает shutdown() для корректного завершения работы
     */
    ~ThreadPool();
    
    /**
     * @brief Принудительная остановка всех потоков пула
     * 
     * Устанавливает флаг остановки, уведомляет все потоки и дожидается их завершения.
     * Гарантирует, что все запущенные задачи будут завершены перед возвратом управления.
     * 
     * @warning После вызова shutdown() добавление новых задач невозможно
     * 
     * @code
     * // Пример корректного завершения
     * pool.shutdown();
     * // pool.enqueue_task(...); // ОШИБКА: пул уже остановлен
     * @endcode
     */
    void shutdown();
    
    /**
     * @brief Добавляет задачу в очередь на выполнение
     * @tparam F Тип задачи (лямбда, функция, функтор, std::function)
     * @param task Задача для выполнения в одном из рабочих потоков
     * 
     * @note Задача выполняется асинхронно в одном из доступных потоков
     * @note Гарантирует порядок выполнения задач (FIFO)
     * @note Потокобезопасна - может вызываться из любого потока
     * 
     * @code
     * // Пример добавления задачи
     * pool.enqueue_task([]() {
     *     std::cout << "Выполняется в фоновом потоке" << std::endl;
     * });
     * @endcode
     */
    template<typename F>
    void enqueue_task(F&& task) {
        {
            std::unique_lock<std::mutex> lock(queue_mutex_);
            tasks_.emplace(std::forward<F>(task));
        }
        condition_.notify_one();
    }
    
private:
    std::vector<std::thread> workers_;       ///< Вектор рабочих потоков пула
    std::queue<std::function<void()>> tasks_; ///< Очередь задач для выполнения
    std::mutex queue_mutex_;                 ///< Мьютекс для защиты доступа к очереди задач
    std::condition_variable condition_;      ///< Условная переменная для синхронизации потоков
    std::atomic<bool> stop_{false};          ///< Атомарный флаг остановки пула
    std::string pool_name_;                  ///< Имя пула для отладки и логирования
};

/**
 * @brief Основной обработчик команд с многопоточной архитектурой
 * 
 * Накопливает команды, формирует пакеты согласно заданному размеру и динамическим блокам,
 * распределяет вывод между потоками консоли и файловыми потоками.
 * 
 * @note Использует 3 фоновых потока: 1 для консоли и 2 для файлов
 * @note Поддерживает динамические блоки команд с помощью фигурных скобок
 * @note Обеспечивает потокобезопасность всех операций
 */
class CommandProcessor {
public:
    /**
     * @brief Конструктор обработчика команд
     * @param bulk_size Размер блока команд для автоматической обработки
     * 
     * @note Создает и запускает фоновые потоки при инициализации
     * @note Размер блока используется только для автоматического завершения блоков
     * 
     * @code
     * // Пример создания обработчика с блоком из 5 команд
     * CommandProcessor processor(5);
     * @endcode
     */
    explicit CommandProcessor(size_t bulk_size);
    
    /**
     * @brief Деструктор обработчика команд
     * 
     * Автоматически обрабатывает оставшиеся команды и останавливает все фоновые потоки.
     * Гарантирует корректное освобождение всех ресурсов.
     * 
     * @note Вызывает flush_remaining() и shutdown()
     */
    ~CommandProcessor();
    
    /**
     * @brief Принудительная остановка всех фоновых потоков
     * 
     * Останавливает потоки вывода в консоль и файлы, дожидается их завершения.
     * После вызова обработчик не может использоваться для обработки команд.
     * 
     * @warning Последующие вызовы process_command() после shutdown() не определены
     */
    void shutdown();
    
    /**
     * @brief Обрабатывает очередную команду
     * @param command Команда для обработки в виде string_view
     * 
     * @note Поддерживает специальные команды "{" и "}" для динамических блоков
     * @note Автоматически завершает блок при достижении bulk_size (вне динамических блоков)
     * @note Потокобезопасна - может вызываться из любого потока
     * 
     * @code
     * // Пример обработки команд
     * processor.process_command("cmd1");
     * processor.process_command("{");     // Начало динамического блока
     * processor.process_command("cmd2");
     * processor.process_command("}");     // Конец динамического блока
     * @endcode
     */
    void process_command(std::string_view command);
    
    /**
     * @brief Принудительная обработка оставшихся команд в буфере
     * 
     * Отправляет все накопленные команды в фоновые потоки для вывода.
     * Если обработчик находится внутри динамического блока, буфер очищается без обработки.
     * 
     * @note Обычно вызывается перед завершением работы обработчика
     * @note Игнорирует команды в незавершенных динамических блоках
     */
    void flush_remaining();
    
private:
    /**
     * @brief Отправляет текущий блок команд на обработку в фоновые потоки
     * 
     * Распределяет блок команд между потоками вывода:
     * - log_thread_pool_: вывод в консоль
     * - file_thread_pool_: запись в файлы (round-robin распределение)
     * 
     * @note Генерирует уникальные имена файлов на основе временных меток
     * @note Очищает буфер команд после успешной отправки
     */
    void flush_commands();
    
    size_t bulk_size_;                                  ///< Размер блока команд для автоматического завершения
    size_t block_depth_{0};                             ///< Текущая глубина вложенности динамических блоков
    std::vector<std::string> commands_;                 ///< Буфер накопленных команд текущего блока
    std::chrono::system_clock::time_point first_command_time_; ///< Временная метка первой команды в текущем блоке
    
    std::mutex console_mutex_;                          ///< Мьютекс для синхронизации вывода в консоль (если требуется)
    std::atomic<size_t> file_writer_index_{0};          ///< Атомарный счетчик для round-robin распределения между файловыми потоками
    
    /**
     * @brief Пул потоков для вывода в консоль
     * 
     * Содержит 1 поток, который асинхронно выводит блоки команд в стандартный вывод.
     * Обеспечивает неблокирующую работу основного потока при выводе.
     */
    std::unique_ptr<ThreadPool> log_thread_pool_;
    
    /**
     * @brief Пул потоков для записи в файлы
     * 
     * Содержит 2 потока, которые асинхронно записывают блоки команд в файлы.
     * Использует round-robin алгоритм для распределения нагрузки между потоками.
     */
    std::unique_ptr<ThreadPool> file_thread_pool_;
};
