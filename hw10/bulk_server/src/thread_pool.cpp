#include "thread_pool.h"

/**
 * @brief Конструктор пула потоков
 * @param num_threads Количество рабочих потоков в пуле
 * @param name Имя пула для отладки и идентификации
 * 
 * @details Создает указанное количество рабочих потоков, которые начинают
 * ожидать задачи в очереди. Каждый поток работает в бесконечном цикле,
 * извлекая и выполняя задачи из очереди.
 * 
 * @note Потоки создаются сразу при построении объекта и начинают
 * обрабатывать задачи сразу после запуска.
 * 
 * @warning Количество потоков должно быть разумным для избежания
 * избыточного потребления ресурсов системы.
 */
ThreadPool::ThreadPool(size_t num_threads, const std::string& name) 
    : pool_name_(name) {
    for (size_t i = 0; i < num_threads; ++i) {
        workers_.emplace_back([this] {
            /**
             * @brief Основной цикл выполнения задач рабочим потоком
             * 
             * @details Каждый рабочий поток выполняет следующий алгоритм:
             * 1. Ожидает появления задачи в очереди или сигнала остановки
             * 2. Извлекает задачу из очереди (если доступна)
             * 3. Выполняет задачу вне критической секции
             * 4. Повторяет цикл до получения сигнала остановки
             * 
             * @note Условная переменная обеспечивает эффективное ожидание
             * без активного опроса очереди.
             */
            while (true) {
                std::function<void()> task;
                {
                    // Критическая секция для доступа к очереди задач
                    std::unique_lock<std::mutex> lock(queue_mutex_);
                    
                    /**
                     * @brief Ожидание условия для пробуждения потока
                     * 
                     * @details Поток блокируется до выполнения одного из условий:
                     * - Установлен флаг остановки (stop_ == true)
                     * - В очереди появилась новая задача (!tasks_.empty())
                     * 
                     * @note Использование предиката предотвращает ложные пробуждения
                     */
                    condition_.wait(lock, [this] {
                        return stop_.load() || !tasks_.empty();
                    });
                    
                    // Проверка условия выхода из цикла
                    if (stop_.load() && tasks_.empty()) return;
                    
                    // Если очередь пуста (ложное пробуждение), продолжаем ожидание
                    if (tasks_.empty()) continue;
                    
                    // Извлекаем задачу из очереди
                    task = std::move(tasks_.front());
                    tasks_.pop();
                } // Критическая секция завершается - мьютекс освобождается
                
                /**
                 * @brief Выполнение задачи
                 * 
                 * @details Задача выполняется вне критической секции,
                 * что позволяет другим потокам одновременно добавлять
                 * новые задачи в очередь.
                 * 
                 * @note Исключения в задачах должны обрабатываться внутри
                 * самой задачи, так как пул потоков их не перехватывает.
                 */
                task();
            }
        });
    }
}

/**
 * @brief Деструктор пула потоков
 * 
 * @details Автоматически вызывает shutdown() для корректного завершения
 * всех рабочих потоков. Гарантирует освобождение всех ресурсов.
 * 
 * @warning Не должен вызываться при наличии активных ссылок на объект
 * @note Если деструктор вызывается без предварительного shutdown(),
 * все невыполненные задачи в очереди будут потеряны.
 */
ThreadPool::~ThreadPool() {
    shutdown();
}

/**
 * @brief Принудительная остановка всех потоков пула
 * 
 * @details Выполняет следующие действия:
 * 1. Устанавливает атомарный флаг остановки
 * 2. Уведомляет все ожидающие потоки через condition_variable
 * 3. Дожидается завершения всех потоков через join()
 * 
 * @note Гарантирует, что все запущенные задачи будут завершены,
 * но задачи, оставшиеся в очереди, выполняться не будут.
 * 
 * @warning После вызова shutdown() добавление новых задач невозможно
 * @note Метод является идемпотентным - повторные вызовы безопасны
 * 
 * @code
 * // Пример использования
 * ThreadPool pool(4);
 * // ... добавление задач ...
 * pool.shutdown(); // Корректное завершение
 * @endcode
 */
void ThreadPool::shutdown() {
    /**
     * @brief Установка флага остановки
     * 
     * @details Атомарная установка флага ensures thread-safe операция
     * без необходимости дополнительной синхронизации.
     */
    stop_.store(true);
    
    /**
     * @brief Уведомление всех ожидающих потоков
     * 
     * @details Пробуждает все потоки, ожидающие на condition_variable,
     * чтобы они могли проверить флаг остановки и завершиться.
     */
    condition_.notify_all();
    
    /**
     * @brief Ожидание завершения всех рабочих потоков
     * 
     * @details Для каждого потока в пуле:
     * - Проверяет, можно ли присоединиться к потоку (joinable)
     * - Вызывает join() для ожидания завершения
     * 
     * @note join() гарантирует, что ресурсы потока будут освобождены
     * и деструктор пула может безопасно завершиться.
     */
    for (std::thread &worker : workers_) {
        if (worker.joinable()) {
            worker.join();
        }
    }
}
