#pragma once

#include <vector>
#include <string>
#include <memory>
#include <mutex>
#include <chrono>
#include <atomic>
#include "observer.h"
#include "thread_pool.h"

/**
 * @class CommandProcessor
 * @brief Обработчик команд с поддержкой паттерна Observer
 * 
 * @details Класс отвечает за накопление, группировку и обработку команд в блоки
 * согласно заданному размеру и правилам динамических блоков. Реализует интерфейс
 * IObservable для уведомления зарегистрированных наблюдателей о сформированных блоках команд.
 * 
 * @note Поддерживает два типа блоков:
 * - Статические блоки: автоматически завершаются при достижении bulk_size
 * - Динамические блоки: ограничиваются символами { и }, игнорируют bulk_size
 * 
 * @see IObservable
 * @see IObserver
 */
class CommandProcessor : public IObservable {
public:
    /**
     * @brief Конструктор обработчика команд
     * @param bulk_size Размер блока команд для автоматической обработки
     * 
     * @details Инициализирует обработчик с заданным размером блока и создает
     * пул потоков для асинхронного уведомления наблюдателей.
     * 
     * @warning Размер блока должен быть положительным числом
     */
    explicit CommandProcessor(size_t bulk_size);
    
    /**
     * @brief Деструктор обработчика команд
     * 
     * @details Автоматически обрабатывает оставшиеся команды и останавливает
     * все фоновые потоки. Гарантирует корректное освобождение ресурсов.
     */
    ~CommandProcessor();
    
    // Основной интерфейс
    
    /**
     * @brief Обрабатывает очередную команду
     * @param command Команда для обработки в виде string_view
     * 
     * @details Обрабатывает команды согласно следующим правилам:
     * - "{" - начинает динамический блок (увеличивает глубину вложенности)
     * - "}" - завершает динамический блок (уменьшает глубину вложенности)
     * - Обычные команды добавляются в текущий блок
     * 
     * @note Автоматически завершает блок при:
     * - Достижении размера bulk_size (вне динамических блоков)
     * - Завершении динамического блока (глубина вложенности становится 0)
     * - Начале нового динамического блока
     * 
     * @note Потокобезопасна - защищена внутренним мьютексом
     */
    void process_command(std::string_view command);
    
    /**
     * @brief Принудительная обработка оставшихся команд в буфере
     * 
     * @details Обрабатывает накопленные команды если обработчик не находится
     * внутри динамического блока. В противном случае очищает буфер без обработки.
     * 
     * @note Используется при завершении работы для обработки последних команд
     * @note Игнорирует команды в незавершенных динамических блоках
     */
    void flush_remaining();
    
    /**
     * @brief Принудительная остановка всех фоновых потоков
     * 
     * @details Останавливает пул потоков для уведомления наблюдателей и
     * дожидается их завершения. После вызова обработчик не может использоваться.
     * 
     * @warning Последующие вызовы process_command() после shutdown() не определены
     * @note Метод является идемпотентным - повторные вызовы безопасны
     */
    void shutdown();
    
    // IObservable interface
    
    /**
     * @brief Подписывает наблюдателя на уведомления
     * @param observer Указатель на наблюдателя для подписки
     * 
     * @details Добавляет наблюдателя в список подписчиков. После подписки
     * наблюдатель будет получать уведомления о всех сформированных блоках команд.
     * 
     * @note Потокобезопасна - защищена мьютексом observers_mutex_
     * @note Один наблюдатель может быть подписан только один раз
     */
    void subscribe(std::shared_ptr<IObserver> observer) override;
    
    /**
     * @brief Отписывает наблюдателя от уведомлений
     * @param observer Указатель на наблюдателя для отписки
     * 
     * @details Удаляет наблюдателя из списка подписчиков. После отписки
     * наблюдатель больше не будет получать уведомления.
     * 
     * @note Потокобезопасна - защищена мьютексом observers_mutex_
     * @note Если наблюдатель не был подписан, метод не выполняет действий
     */
    void unsubscribe(std::shared_ptr<IObserver> observer) override;
    
    /**
     * @brief Уведомляет всех подписанных наблюдателей о новом блоке команд
     * @param commands Вектор команд в блоке
     * @param timestamp Временная метка создания блока
     * @param context_id Идентификатор контекста (соединения)
     * 
     * @details Отправляет асинхронные уведомления всем зарегистрированным
     * наблюдателям через пул потоков. Не блокирует вызывающий поток.
     * 
     * @note Уведомления выполняются в порядке подписки наблюдателей
     * @note Если наблюдатель выбросит исключение, оно будет проигнорировано
     */
    void notify(const std::vector<std::string>& commands, 
                time_t timestamp, 
                void* context_id) override;

private:
    /**
     * @brief Отправляет текущий блок команд на обработку наблюдателям
     * 
     * @details Выполняет следующие действия:
     * 1. Создает копию блока команд для передачи в потоки
     * 2. Преобразует временную метку в time_t
     * 3. Вызывает notify() для уведомления наблюдателей
     * 4. Очищает буфер команд для приема новых данных
     * 
     * @note Вызывается автоматически при завершении блока
     * @note Работает с копией данных для обеспечения потокобезопасности
     */
    void flush_commands();
    
    size_t bulk_size_;                                  ///< Размер блока команд для автоматического завершения
    size_t block_depth_{0};                             ///< Текущая глубина вложенности динамических блоков
    std::vector<std::string> commands_;                 ///< Буфер накопленных команд текущего блока
    std::chrono::system_clock::time_point first_command_time_; ///< Временная метка первой команды в текущем блоке
    std::mutex command_mutex_;                          ///< Мьютекс для защиты доступа к буферу команд
    
    // Поддержка Observer
    std::vector<std::shared_ptr<IObserver>> observers_; ///< Список подписанных наблюдателей
    std::mutex observers_mutex_;                        ///< Мьютекс для защиты доступа к списку наблюдателей
    
    // Пул потоков для асинхронного уведомления
    std::unique_ptr<ThreadPool> notification_pool_;     ///< Пул потоков для асинхронных уведомлений наблюдателей
};
