#pragma once
#include <string>
#include <vector>

/**
 * @brief Структура, представляющая строку таблицы с идентификатором и именем
 * 
 * Данная структура используется для хранения данных одной строки таблицы,
 * где id - уникальный идентификатор, а name - текстовое значение.
 */
struct TableRow {
    int id;           ///< Уникальный идентификатор строки (первичный ключ)
    std::string name; ///< Текстовое значение строки
    
    /**
     * @brief Конструктор структуры TableRow
     * @param id Уникальный идентификатор строки
     * @param name Текстовое значение строки
     */
    TableRow(int id, std::string name) : id(id), name(std::move(name)) {}
};

/**
 * @brief Структура, представляющая всю таблицу с данными
 * 
 * Содержит название таблицы и коллекцию строк TableRow.
 * Используется для организации данных таблиц A и B.
 */
struct TableData {
    std::string name;               ///< Название таблицы (A или B)
    std::vector<TableRow> rows;     ///< Вектор строк таблицы
};

/**
 * @brief Структура для хранения результатов операций над множествами
 * 
 * Используется для возврата результатов операций INTERSECTION и SYMMETRIC_DIFFERENCE.
 * Содержит коллекцию результирующих строк, флаг успеха и сообщение об ошибке.
 */
struct OperationResult {
    /**
     * @brief Структура, представляющая одну строку результата операции
     * 
     * Содержит идентификатор и значения из обеих таблиц для операций пересечения
     * и симметрической разности.
     */
    struct ResultRow {
        int id;                     ///< Идентификатор строки результата
        std::string column_a;       ///< Значение из таблицы A (может быть пустым)
        std::string column_b;       ///< Значение из таблицы B (может быть пустым)
    };
    
    std::vector<ResultRow> rows;    ///< Вектор результирующих строк операции
    bool success;                   ///< Флаг успешного выполнения операции
    std::string error_message;      ///< Сообщение об ошибке (если success = false)
};
