/**
 * @file server.cpp
 * @brief Реализация класса сервера для обработки операций над множествами
 */

#include "server.h"
#include <iostream>

/**
 * @brief Конструктор сервера
 * 
 * @param io_context Контекст ввода-вывода Boost.Asio
 * @param port Порт для прослушивания входящих соединений
 * 
 * @details Создает сервер, который прослушивает указанный порт на всех сетевых интерфейсах.
 * Инициализирует базу данных в памяти и репозиторий для работы с таблицами.
 * После инициализации начинает принимать входящие соединения.
 */
Server::Server(boost::asio::io_context& io_context, short port)
    : acceptor_(io_context, tcp::endpoint(tcp::v4(), port)), // Инициализация акцептора на указанном порту
      db_(std::make_shared<Database>()),                     // Создание базы данных в памяти
      repository_(std::make_shared<TableRepository>(db_)) {  // Создание репозитория для работы с таблицами
    std::cout << "Server started on port " << port << std::endl;
    do_accept(); // Начало приема входящих соединений
}

/**
 * @brief Асинхронный прием входящих соединений
 * 
 * @details Метод запускает асинхронное ожидание входящих соединений.
 * При подключении нового клиента создается фабрика команд, обработчик команд
 * и сессия для взаимодействия с клиентом.
 * 
 * Цикл приема соединений продолжается бесконечно благодаря рекурсивному вызову
 * do_accept() в обработчике завершения.
 */
void Server::do_accept() {
    /**
     * @brief Лямбда-обработчик принятия соединения
     * 
     * @param ec Код ошибки Boost.System
     * @param socket Сокет для общения с клиентом
     * 
     * @details Обработчик вызывается при установлении нового соединения или ошибке.
     * При успешном соединении создается цепочка объектов для обработки команд:
     * 1. CommandFactory - для создания объектов команд из строк запросов
     * 2. CommandHandler - для выполнения созданных команд
     * 3. Session - для управления сетевым взаимодействием с клиентом
     * 
     * Сессия запускается в отдельном shared_ptr для управления временем жизни.
     * При ошибке соединения выводится сообщение, но сервер продолжает работу.
     */
    acceptor_.async_accept(
        [this](boost::system::error_code ec, tcp::socket socket) {
            if (!ec) {
                std::cout << "New client connected" << std::endl;
                
                // Создание фабрики команд с доступом к репозиторию данных
                auto factory = std::make_unique<CommandFactory>(repository_);
                
                // Создание обработчика команд с передачей фабрики
                auto handler = std::make_unique<CommandHandler>(std::move(factory));
                
                // Создание и запуск сессии для нового клиента
                // Использование make_shared для корректного управления временем жизни
                std::make_shared<Session>(std::move(socket), std::move(handler))->start();
            } else {
                // Вывод ошибки соединения без прерывания работы сервера
                std::cout << "Accept error: " << ec.message() << std::endl;
            }
            
            // Рекурсивный вызов для приема следующего соединения
            // Обеспечивает непрерывную работу сервера
            do_accept();
        });
}
